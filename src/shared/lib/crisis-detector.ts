/**
 * Синхронная проверка текста на наличие кризисных ключевых слов.
 * Возвращает true, если обнаружены признаки суицидальных мыслей,
 * самоповреждения, панической атаки или тяжёлого кризиса.
 *
 * Паттерны — только русскоязычные.
 */

const CRISIS_PATTERNS: RegExp[] = [
  // Суицидальные мысли
  /не хочу жить/i,
  /лучше умереть/i,
  /хочу исчезнуть/i,
  /не вижу смысла/i,
  /конец всему/i,
  /хочу умереть/i,
  /жить не хочу/i,
  /покончить с собой/i,
  /самоубийств/i,
  /убить себя/i,
  /свести счёты/i,

  // Самоповреждение
  /порез/i,
  /режу себя/i,
  /раню себя/i,

  // Безнадёжность / отчаяние
  /нет выхода/i,
  /не вижу выхода/i,
  /безнадёга/i,
  /бесполезно/i,
  /никчему/i,

  // Тяжёлые состояния
  /не могу больше/i,
  /уже не могу/i,
  /хочу всё бросить/i,
  /не справляюсь/i,
  /больше нет сил/i,
  /крайне тяжело/i,
  /больше не вынесу/i,

  // Панические реакции
  /паническая атака/i,
  /дышать не могу/i,
  /сердце выпрыгивает/i,
  /сводит с ума/i,
  /теряю контроль/i,
  /оторвётся/i,
  /умираю/i,
];

export function checkCrisisKeywords(text: string): boolean {
  if (!text || text.trim().length === 0) return false;
  return CRISIS_PATTERNS.some((pattern) => pattern.test(text));
}
